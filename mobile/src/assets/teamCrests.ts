/**
 * The crest for a team name, or null when none was verified.
 *
 * Matching is exact first, then case-insensitive, so a club whose canonical name
 * differs only in capitalisation still gets its crest while a genuinely unknown
 * name does not silently borrow a similarly-spelled club's badge.
 */
export function crestForTeam(name: string | null | undefined): string | null {
  if (!name) return null;
  if (TEAM_CRESTS[name]) return TEAM_CRESTS[name];
  const lower = name.toLowerCase();
  const key = Object.keys(TEAM_CRESTS).find((candidate) => candidate.toLowerCase() === lower);
  return key ? TEAM_CRESTS[key] : null;
}
